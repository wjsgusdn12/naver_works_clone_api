-- 게시글 이모지 리액션. 채팅과 같이 한 사람은 글마다 이모지 하나만(다른 걸 누르면 바뀜).
CREATE TABLE board_post_reaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,
    emoji VARCHAR(40) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_board_post_reaction_post FOREIGN KEY (post_id) REFERENCES board_post (id),
    CONSTRAINT fk_board_post_reaction_membership FOREIGN KEY (membership_id) REFERENCES membership (id),
    CONSTRAINT uk_board_post_reaction UNIQUE (post_id, membership_id)
);

-- 글 목록 한 페이지의 리액션 수를 글 ID 묶음으로 세는 조회에 맞춘 인덱스.
CREATE INDEX idx_board_post_reaction_post ON board_post_reaction (post_id);
