-- 게시판. 회사마다 공지사항(NOTICE)·자유게시판(FREE)·문의하기(INQUIRY)·회사 게시판(COMPANY) 하나씩,
-- 부서마다 부서 게시판(DEPARTMENT) 하나. 회사·부서 게시판은 관리자가 이름을 바꿀 수 있음.
CREATE TABLE board (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company (id),
    department_id BIGINT NULL REFERENCES department (id),
    type VARCHAR(20) NOT NULL,
    name VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_board_type CHECK (type IN ('NOTICE', 'FREE', 'INQUIRY', 'COMPANY', 'DEPARTMENT')),
    CONSTRAINT ck_board_department CHECK ((type = 'DEPARTMENT') = (department_id IS NOT NULL))
);
-- 같은 회사에 같은 종류의 회사 단위 게시판은 하나, 부서 게시판은 부서마다 하나(동시에 만들려 해도 한 번만 생김).
CREATE UNIQUE INDEX uk_board_company_type ON board (company_id, type) WHERE department_id IS NULL;
CREATE UNIQUE INDEX uk_board_department ON board (department_id) WHERE department_id IS NOT NULL;

-- 게시글. content_json: 편집기(Tiptap) 문서를 서버가 허용한 형식만 남겨 다시 만든 JSON, content_text: 검색·미리보기용 글자.
-- important: 목록 맨 위 고정, must_read: 필독(읽음 확인). answered_at: 문의하기 글에 관리자가 처음 댓글을 단 시각.
-- deleted_at: 휴지통으로 옮긴 시각(실제로 지우지 않음, 복구하면 NULL).
CREATE TABLE board_post (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id BIGINT NOT NULL REFERENCES board (id),
    author_membership_id BIGINT NOT NULL REFERENCES membership (id),
    title VARCHAR(200) NOT NULL,
    content_json TEXT NOT NULL,
    content_text TEXT NOT NULL,
    important BOOLEAN NOT NULL,
    must_read BOOLEAN NOT NULL,
    view_count INT NOT NULL,
    comment_count INT NOT NULL,
    answered_at TIMESTAMP WITH TIME ZONE NULL,
    deleted_at TIMESTAMP WITH TIME ZONE NULL,
    deleted_by_membership_id BIGINT NULL REFERENCES membership (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NULL,
    version BIGINT NOT NULL
);
CREATE INDEX idx_board_post_board ON board_post (board_id, id DESC);
CREATE INDEX idx_board_post_author ON board_post (author_membership_id, id DESC);

-- 누가 어떤 글을 읽었는지(조회수·필독 읽음 확인). 한 사람은 글마다 한 번만.
CREATE TABLE board_post_read (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES board_post (id),
    membership_id BIGINT NOT NULL REFERENCES membership (id),
    read_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_board_post_read UNIQUE (post_id, membership_id)
);

CREATE TABLE board_comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES board_post (id),
    author_membership_id BIGINT NOT NULL REFERENCES membership (id),
    content VARCHAR(1000) NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_board_comment_post ON board_comment (post_id, id);

-- 첨부(본문 속 사진 포함). 글을 쓰는 중에 먼저 올리므로 post_id는 저장 전까지 NULL.
-- inline: 본문 속에 들어간 사진이면 true(아래 첨부 목록에는 안 보임).
CREATE TABLE board_attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NULL REFERENCES board_post (id),
    uploader_membership_id BIGINT NOT NULL REFERENCES membership (id),
    kind VARCHAR(10) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    storage_key VARCHAR(100) NOT NULL,
    thumbnail_key VARCHAR(100) NULL,
    width INT NULL,
    height INT NULL,
    inline BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_board_attachment_kind CHECK (kind IN ('IMAGE', 'FILE'))
);
CREATE INDEX idx_board_attachment_post ON board_attachment (post_id);
CREATE INDEX idx_board_attachment_uploader ON board_attachment (uploader_membership_id, created_at);
-- 청소 작업: 디스크 파일 중 게시판 첨부가 쓰는 것을 찾을 때.
CREATE INDEX idx_board_attachment_storage_key ON board_attachment (storage_key);
CREATE INDEX idx_board_attachment_thumbnail_key ON board_attachment (thumbnail_key);

-- 게시판 즐겨찾기(사이드바).
CREATE TABLE board_favorite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id BIGINT NOT NULL REFERENCES membership (id),
    board_id BIGINT NOT NULL REFERENCES board (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_board_favorite UNIQUE (membership_id, board_id)
);

-- 이미 있는 회사·부서의 게시판을 미리 만듦. 이후 생기는 회사·부서는 게시판 화면을 열 때 서버가 만듦.
INSERT INTO board (company_id, department_id, type, name, created_at)
SELECT company.id, NULL, kind.type, kind.name, CURRENT_TIMESTAMP
FROM company
CROSS JOIN (VALUES ('NOTICE', '공지사항'), ('FREE', '자유게시판'), ('INQUIRY', '문의하기')) AS kind (type, name);

INSERT INTO board (company_id, department_id, type, name, created_at)
SELECT company.id, NULL, 'COMPANY', LEFT(company.name, 30), CURRENT_TIMESTAMP
FROM company;

INSERT INTO board (company_id, department_id, type, name, created_at)
SELECT department.company_id, department.id, 'DEPARTMENT', LEFT(department.name, 30), CURRENT_TIMESTAMP
FROM department
WHERE department.enabled = TRUE;
