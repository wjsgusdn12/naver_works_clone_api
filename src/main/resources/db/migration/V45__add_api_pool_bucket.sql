-- API 대시보드의 DB 연결 풀 그래프를 기간 탭(최근 60분·24시간·7일·30일)에 맞춰 보여 주려고 DB에 보관.
-- unit: 칸 길이(MINUTE 1분 · FIVE_MINUTES 5분 · HOUR 1시간). 칸 자리(slot)는 단위별로 개수를 고정하고 돌려 씀
-- (1분 70자리 · 5분 300자리 · 1시간 744자리). 같은 자리에 옛 칸이 남아 있으면 새 칸으로 덮어써 행 수가 늘지 않음.
-- 서버 여러 대가 같은 행에 기록: 최대값(max_active·max_waiting·max_size)은 큰 쪽, 합(sum_active·samples)은 더하기.
-- 평균 사용 = sum_active / samples (서버 한 대 기준 평균).
CREATE TABLE api_pool_bucket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit VARCHAR(20) NOT NULL,
    slot INTEGER NOT NULL,
    bucket BIGINT NOT NULL,
    max_active INTEGER NOT NULL DEFAULT 0,
    sum_active BIGINT NOT NULL DEFAULT 0,
    samples BIGINT NOT NULL DEFAULT 0,
    max_waiting INTEGER NOT NULL DEFAULT 0,
    max_size INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_api_pool_bucket UNIQUE (unit, slot)
);

-- 기간 조회(단위 + 칸 번호 범위)에 맞춘 인덱스.
CREATE INDEX idx_api_pool_bucket_unit_bucket ON api_pool_bucket (unit, bucket);
