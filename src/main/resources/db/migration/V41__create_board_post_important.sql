-- 게시글 "중요" 개인 표시. 각자 자기 목록용으로 글에 깃발을 꽂음(다른 사람에게는 보이지 않음).
-- 예전 글쓴이용 중요(board_post.important)는 더 쓰지 않음(컬럼은 그대로 둠).
CREATE TABLE board_post_important (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_board_post_important_post FOREIGN KEY (post_id) REFERENCES board_post (id),
    CONSTRAINT fk_board_post_important_membership FOREIGN KEY (membership_id) REFERENCES membership (id),
    CONSTRAINT uk_board_post_important UNIQUE (post_id, membership_id)
);

-- "중요" 목록(내가 표시한 글)을 찾는 조회에 맞춘 인덱스.
CREATE INDEX idx_board_post_important_member ON board_post_important (membership_id);
