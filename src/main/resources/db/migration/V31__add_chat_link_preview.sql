-- 메시지 속 링크의 미리보기(웹사이트 제목·대표 이미지). 같은 주소는 한 번만 가져와 모든 방이 같이 씀.
-- url_hash: 주소의 SHA-256(긴 주소도 고정 길이로 찾기 위해). status: PENDING(가져오는 중)·DONE(완료)·FAILED(실패).
-- image_key: 서버가 받아 줄여 저장한 대표 이미지의 위치 키(없으면 NULL), image_type: 그 이미지 형식.
CREATE TABLE chat_link_preview (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_hash VARCHAR(64) NOT NULL,
    url VARCHAR(2048) NOT NULL,
    title VARCHAR(300) NULL,
    image_key VARCHAR(100) NULL,
    image_type VARCHAR(20) NULL,
    status VARCHAR(10) NOT NULL,
    fetched_at TIMESTAMP WITH TIME ZONE NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_chat_link_preview_url_hash UNIQUE (url_hash),
    CONSTRAINT ck_chat_link_preview_status CHECK (status IN ('PENDING', 'DONE', 'FAILED'))
);

-- 청소 작업: 디스크 파일 중 링크 대표 이미지가 쓰는 것을 찾을 때.
CREATE INDEX idx_chat_link_preview_image_key ON chat_link_preview (image_key);
